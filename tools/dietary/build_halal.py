#!/usr/bin/env python3
"""Build web/lib/mm/halal-data.ts from data/dietary/halal-*.csv (what each chain's OWN website says about halal food).

    python3 tools/dietary/build_halal.py [--check]

Rows: chain_id,scope,statement,source_url,checked_on. Only `all` (the chain says all its UK food/meat is halal) and `some` (some
restaurants or some meat) are published, each with the chain's own words and the page they are on; `no` and `not_stated` are never published.
A row without a quote or a source page is refused (the app never says halal without the restaurant's own words).

When a chain has several rows (in different files), the LATEST one decides, latest = the newest `checked_on`, and for the same date the
file that sorts last: a later `all`/`some` replaces an earlier one, and a later `no` (the chain now says in its own words that it is not
halal) removes an earlier `all`/`some`. `not_stated` (we could not find or read anything) never changes what an earlier row says.
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data" / "dietary"
OUT = ROOT / "web" / "lib" / "mm" / "halal-data.ts"


def load_rows(src: Path, published: set[str]) -> tuple[dict[str, dict], list[str], list[str]]:
    """The halal statements to publish: ({chain_id: row}, errors, skipped chain ids). See the module docstring for how rows override."""
    found: list[tuple[str, str, int, str, dict]] = []   # (checked_on, file name, row number, chain id, row)
    for f in sorted(src.glob("halal-*.csv")):
        with open(f, newline="", encoding="utf-8") as fh:
            for n, r in enumerate(csv.DictReader(fh)):
                found.append(((r.get("checked_on") or "").strip(), f.name, n, (r.get("chain_id") or "").strip(), r))
    found.sort(key=lambda t: t[:3])
    rows: dict[str, dict] = {}
    errors: list[str] = []
    skipped: list[str] = []
    for checked, fname, _n, cid, r in found:
        scope = (r.get("scope") or "").strip()
        if scope == "no":
            rows.pop(cid, None)   # the chain's own later words say it is not halal
            continue
        if scope not in ("all", "some"):
            continue
        statement, url = (r.get("statement") or "").strip(), (r.get("source_url") or "").strip()
        if not statement or not url.startswith("https://"):
            errors.append(f"build_halal: {fname} {cid}: a {scope} row needs the chain's own words and an https page")
            continue
        if cid not in published:
            if cid not in skipped:
                skipped.append(cid)
            continue
        rows[cid] = {"scope": scope, "statement": statement, "url": url, "checkedOn": checked}
    return rows, errors, skipped


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    published = {p.name.removeprefix("chain-").removesuffix(".json") for p in (ROOT / "web" / "public" / "menus").glob("chain-*.json")}
    rows, errors, skipped = load_rows(SRC, published)
    for cid in skipped:
        print(f"build_halal: skipping {cid} (not a published chain)")
    for e in errors:
        print(e, file=sys.stderr)
    if errors:
        return 1
    body = ",\n".join(f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}" for k, v in sorted(rows.items()))
    ts = (
        "// GENERATED by tools/dietary/build_halal.py from data/dietary/halal-*.csv: do not edit by hand.\n"
        "// What each chain's own website says about halal food (scope \"all\" = all its UK food/meat, \"some\" = some restaurants or some meat).\n"
        "export interface HalalStatement { scope: \"all\" | \"some\"; statement: string; url: string; checkedOn: string }\n\n"
        f"export const HALAL: Readonly<Record<string, HalalStatement>> = {{\n{body}{',' if body else ''}\n}};\n"
    )
    if args.check:
        print(f"{len(rows)} chains: {sum(r['scope'] == 'all' for r in rows.values())} all, {sum(r['scope'] == 'some' for r in rows.values())} some")
        return 0
    OUT.write_text(ts, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} chains")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

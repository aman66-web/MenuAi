export interface ShopFile {
  v: 1;
  retailer: string;
  name: string;
  checkedOn: string;
  /** The shop's product page is pageBase + id (or + the row's page path; or, with pageSearch, + the product's name: the shop's own search for it). */
  pageBase: string;
  pageSearch?: boolean;
  /** Where a row's page path is read from when the shop's product pages are not under pageBase (M&S: pageBase is its search, its range's pages are under
   *  https://www.marksandspencer.com/food/). Absent = pageBase. */
  pageRoot?: string;
  /** Why a row has no price ("Price in store"): "offers" (Lidl: the website prices only its weekly offers; the default) or "stores" (M&S: its aisle pages list no price for these products; the site asks for a store, and what it shows after one is chosen has not been seen, so the app only says the lists have none). */
  priceNote?: "offers" | "stores";
  /** The shop's picture of a product is photoBase + photoId + "/image.jpg" (Sainsbury's), or photoTemplate with photoId in place of "{photo}". */
  photoBase: string;
  photoTemplate?: string;
  categories: string[];
  schemes: string[];
  /** The earliest day a product page's nutrition was read (empty when none was). */
  nutritionCheckedOn?: string;
  products: ShopRow[];
}

export interface ShopManifest {
  v: 1;
  /** `nutrition`: how many products have numbers read from their own page (recipes need them; absent = none). */
  /** `priced`: how many show a price (absent = all of them; fewer only for Lidl and M&S, whose everyday ranges are listed with no price). */
  /** `community`: how many of the `nutrition` products have community numbers for their barcode instead (ShopNutrition.community). */
  retailers: Array<{ id: string; name: string; file: string; count: number; checkedOn: string; sha256: string; nutrition?: number; community?: number; priced?: number }>;
}

/** The shops recipes can use: only those with products whose label we have read (recipes work out every figure from the labels). */
/**
 * A shop counts for recipes once it can make at least this many of our recipes entirely from its own products with read labels (lib/mm/recipeCoverage.ts,
 * generated by tests/recipeCoverage.test.ts). Fewer would leave a person who shops only there with a handful of recipes (Iceland: 14 of 165 on 2026-11-17),
 * so such a shop waits until more of its labels are read. A shop the table doesn't know (tests' made-up shops) counts as soon as it has labels.
 */
export const MIN_RECIPE_COVERAGE = 80;
export const recipeShops = (m: ShopManifest | null): ShopManifest["retailers"] =>
  m ? m.retailers.filter((r) => (r.nutrition ?? 0) > 0 && (RECIPE_COVERAGE[r.id] === undefined || RECIPE_COVERAGE[r.id]! >= MIN_RECIPE_COVERAGE)) : [];

/**
 * The shop a recipe is made for (founder 2026-11-17: "every single recipe is tailored for a specific store ... we don't mix them"): the one asked for (a link's ?r=)
 * when its labels are read, else the first of the person's own supermarkets whose labels we've read, else the first shop that is ready. One shop, in a list of
 * one so the screens that read "the shops" keep working; empty while the manifest isn't known or no shop is ready. Another shop's product comes into a recipe only
 * when the person swaps one ingredient to it (RecipeDetail's Swap), never by default.
 */
export function recipeShopSet(manifest: ShopManifest | null, asked: string | null, mine: readonly string[] | undefined): string[] {
  // Only shops whose product labels we have read: a list with names and prices alone can't make a recipe.
  const shops = recipeShops(manifest);
  if (shops.length === 0) return [];
  const has = (id: string | null | undefined): id is string => !!id && shops.some((r) => r.id === id);
  if (has(asked)) return [asked];
  for (const id of mine ?? []) if (has(id)) return [id];
  return [shops[0]!.id];
}

/** Every shop recipes can use, the recipe's own shop first: the shops a recipe page loads (the first is its shop; the others offer a switch and a Swap). */
export function recipeShopsFrom(manifest: ShopManifest | null, base: string | null): string[] {
  const ids = recipeShops(manifest).map((r) => r.id);
  return base && ids.includes(base) ? [base, ...ids.filter((id) => id !== base)] : ids;
}

/** Per 100 g or 100 ml, as the shop's own product page printed them ("<0.5" counted as 0). */
export interface ShopNutrition {
  kcal: number;
  protein: number;
  carbs: number;
  fat: number;
  saturates: number | null;
  sugars: number | null;
  fibre: number | null;
  salt: number | null;
  kj: number | null;
  per: "g" | "ml";
  /** "" when the numbers are for the food as sold; otherwise the word the page's own heading adds ("grilled", "cooked bacon", "prepared"), which the app shows next to them. */
  state: string;
  /** Set when we haven't read the product's own page and the numbers are Open Food Facts contributors' record for exactly its barcode (community data, from
   *  the barcode catalogue; tools/groceries/build_all_products.py catalogue_nutrition). Every screen showing them says so (founder 2026-11-17: recipes for
   *  every supermarket in the app). */
  community?: true;
  /** Set when the numbers were read from ANOTHER supermarket's page for exactly the same product (the same barcode, or the same branded name and pack size;
   *  never a shop's own brand): that shop's id (tools/groceries/build_all_products.py fill_same_product_nutrition; founder 2026-11-17). A real label, so
   *  recipes treat it like the shop's own; the product page says whose page it is from. */
  sameAs?: string;
  /** Set for loose fresh fruit and vegetables with no label of any kind: the UK government's figures for that food, raw (McCance and Widdowson's Composition of
   *  Foods Integrated Dataset 2021; tools/groceries/cofid.py; founder 2026-11-17), and this is the dataset's own name for the food ("Onions, raw"). */
  govFood?: string;
}

export interface ShopProduct {
  id: string;
  name: string;
  /** null only where the shop's own page prints no price (Lidl's everyday range: Lidl prices online only its weekly offers; M&S's everyday food range: its aisle
   *  pages list no price for it). The app says "Price in store". */
  price: number | null;
  unitPrice: number | null;
  /** "per kg", "per litre", "each". */
  unit: string;
  member: { amount: number; scheme: string } | null;
  category: string;
  photoId: string;
  /** The product page's path after pageBase, where it isn't pageBase + id ("" or absent otherwise). */
  page?: string;
  /** Set only where the shop's own product page was read and showed a barcode: the full product page in the app is /app/groceries/product?code=. */
  gtin: string;
  /** Set only where the product's own page was read. */
  nutrition: ShopNutrition | null;
  /** Only where the shop's listing showed no picture: the same product's photo from another supermarket's own website, or the Open Food Facts front photo
   *  of its exact barcode (founder 2026-10-11; tools/groceries/build_all_products.py fill_photos). `from` is that shop's id, or "off". */
  otherPhoto?: { src: string; from: string };
  /** Set only on a recipe's products from several shops at once (tagShopProducts): the shop's id, and its place in the person's order of shops (0 =
   *  the one ticked first, used first). Never in a shop's own file. */
  shop?: string;
  shopRank?: number;
}

/** A product's key that can't mix up two shops whose ids happen to be the same: "<shop>:<id>" on a product tagged with its shop, else its own id. */
export const productKey = (p: Pick<ShopProduct, "id" | "shop">): string => (p.shop ? `${p.shop}:${p.id}` : p.id);

/** Several shops' products as one list for recipes (founder 2026-11-17: "add more stores that they want to source ingredients from"): each product is a COPY
 *  tagged with its shop and that shop's place in the order given (the decoded lists, which other screens share, are never changed). */
export function tagShopProducts(lists: ReadonlyArray<{ shop: string; products: readonly ShopProduct[] }>): ShopProduct[] {
  const out: ShopProduct[] = [];
  lists.forEach(({ shop, products }, shopRank) => {
    for (const p of products) out.push({ ...p, shop, shopRank });
  });
  return out;
}

/** A product with a shelf price: recipes and anything that adds up money use only these. */
export type PricedProduct = ShopProduct & { price: number };
export const hasPrice = (p: ShopProduct): p is PricedProduct => p.price !== null;

export function isShopFile(x: unknown): x is ShopFile {
  const f = x as ShopFile;
  return !!f && f.v === 1 && typeof f.retailer === "string" && typeof f.pageBase === "string" && f.pageBase.startsWith("https://") && Array.isArray(f.categories) && Array.isArray(f.schemes) && Array.isArray(f.products)
    && (f.pageRoot === undefined || (typeof f.pageRoot === "string" && f.pageRoot.startsWith("https://")))
    && (f.priceNote === undefined || f.priceNote === "offers" || f.priceNote === "stores");
}

export function isShopManifest(x: unknown): x is ShopManifest {
  const m = x as ShopManifest;
  return !!m && m.v === 1 && Array.isArray(m.retailers);
}

const ID = /^[A-Za-z0-9][A-Za-z0-9\-_.%]{0,119}$/;
// A picture id put into a shop's photoTemplate, and a page path put after pageBase: the characters those addresses use, never "..".
const PHOTO_ID = /^[A-Za-z0-9_\-./:=%]{1,400}$/;
const PAGE_PATH = /^[A-Za-z0-9][A-Za-z0-9\-_.%/]{0,199}$/;
const safe = (v: unknown, re: RegExp): v is string => typeof v === "string" && re.test(v) && !v.includes("..");
const templated = (f: Pick<ShopFile, "photoTemplate">) => typeof f.photoTemplate === "string" && f.photoTemplate.startsWith("https://") && f.photoTemplate.includes("{photo}");

/**
 * "per 100 g", or "per 100 g (grilled)" when the page's own heading says the numbers are for the grilled, cooked or prepared food
 * (the state word is the shop's own, shown as printed).
 */
export const nutritionBasis = (n: Pick<ShopNutrition, "per" | "state">, t: T = englishT): string =>
  n.state ? t("per 100 {unit} ({state})", { unit: n.per, state: n.state }) : t("per 100 {unit}", { unit: n.per });

function decodeNutrition(n: ShopNutritionRow | null | undefined): ShopNutrition | null {
  if (!Array.isArray(n) || n.length < 10) return null;
  const [kcal, protein, carbs, fat, saturates, sugars, fibre, salt, kj, per, state, source, food] = n;
  if (![kcal, protein, carbs, fat].every((v) => typeof v === "number" && Number.isFinite(v)) || (per !== "g" && per !== "ml")) return null;
  const opt = (v: number | null) => (typeof v === "number" ? v : null);
  return { kcal, protein, carbs, fat, saturates: opt(saturates), sugars: opt(sugars), fibre: opt(fibre), salt: opt(salt), kj: opt(kj), per, state: typeof state === "string" && /^[a-z][a-z ]{0,23}$/.test(state) ? state : "",
    ...(source === "off" ? { community: true as const } : {}), ...(typeof source === "string" && /^same:[a-z][a-z-]{1,30}$/.test(source) ? { sameAs: source.slice(5) } : {}),
    ...(source === "cofid" && typeof food === "string" && food.length > 0 && food.length <= 80 ? { govFood: food } : {}) };
}

// Where a borrowed photo may come from: the supermarkets' own image servers and Open Food Facts' (https only, checked again here).
const OTHER_PHOTO_HOSTS: readonly string[] = PHOTO_HOSTS;
const OTHER_FROM = /^(?:off|[a-z][a-z-]{1,30})$/;

function decodeOtherPhoto(x: unknown): ShopProduct["otherPhoto"] {
  if (!Array.isArray(x) || x.length !== 2 || typeof x[0] !== "string" || typeof x[1] !== "string" || !OTHER_FROM.test(x[0])) return undefined;
  try {
    const u = new URL(x[1]);
    return u.protocol === "https:" && OTHER_PHOTO_HOSTS.includes(u.hostname) && (x[0] === "off") === (u.hostname === "images.openfoodfacts.org") ? { src: u.href, from: x[0] } : undefined;
  } catch {
    return undefined;
  }
}

/** Rows to products; a row that doesn't have the right shape is dropped, never guessed at. */
export function decodeShopProducts(f: ShopFile): ShopProduct[] {
  const out: ShopProduct[] = [];
  for (const r of f.products) {
    if (!Array.isArray(r) || r.length < 10) continue;
    const [id, name, price, unitPrice, unit, member, scheme, cat, photoId, gtin, n, page, other] = r;
    if (typeof id !== "string" || !ID.test(id) || typeof name !== "string" || (price !== null && (typeof price !== "number" || !(price > 0)))) continue;
    const m = typeof member === "number" && price !== null && scheme !== null && f.schemes[scheme] ? { amount: member, scheme: f.schemes[scheme] } : null;
    out.push({ id, name, price, unitPrice: typeof unitPrice === "number" && price !== null ? unitPrice : null, unit: unit || "", member: m, category: f.categories[cat] ?? "Other", photoId: templated(f) ? (safe(photoId, PHOTO_ID) ? photoId : "") : /^\d+$/.test(photoId) ? photoId : "", page: safe(page, PAGE_PATH) ? page : "", gtin: gtin || "", nutrition: decodeNutrition(n), ...(decodeOtherPhoto(other) ? { otherPhoto: decodeOtherPhoto(other) } : {}) });
  }
  return out;
}

/** The shop's own page for a product (https only): its page path (under pageRoot where the shop has one, else pageBase), else the shop's own search for its name
 *  (pageSearch), else pageBase + id. */
export function shopPageUrl(f: Pick<ShopFile, "pageBase" | "pageSearch" | "pageRoot">, p: Pick<ShopProduct, "id" | "name"> & { page?: string }): string {
  if (p.page) return `${f.pageRoot ?? f.pageBase}${p.page}`;
  if (f.pageSearch) return `${f.pageBase}${encodeURIComponent(p.name)}`;
  return `${f.pageBase}${p.id}`;
}

/**
 * Where a list product's picture comes from, best first: the shop's own photo, then (only where its listing showed none) the same product's photo from
 * another supermarket's website or from Open Food Facts. The screen credits each one by name.
 */
export function shopPhotoSources(f: Pick<ShopFile, "retailer" | "photoBase" | "photoTemplate">, p: Pick<ShopProduct, "photoId" | "otherPhoto">): PhotoSource[] {
  const own = shopPhotoUrl(f, p);
  const found: PhotoSource[] = own ? [{ src: own, from: "retailer", shop: f.retailer }]
    : p.otherPhoto ? [p.otherPhoto.from === "off" ? { src: p.otherPhoto.src, from: "off", shop: "" } : { src: p.otherPhoto.src, from: "retailer", shop: p.otherPhoto.from }] : [];
  return found.filter((s) => !(s.shop && isTakenDown(`shop:${s.shop}`))); // a shop on the taken-down list shows no photos
}

/** The shop's picture of a product, or undefined when its listing showed none. */
export function shopPhotoUrl(f: Pick<ShopFile, "photoBase" | "photoTemplate">, p: Pick<ShopProduct, "photoId">): string | undefined {
  if (!p.photoId) return undefined;
  if (f.photoTemplate !== undefined) return templated(f) && safe(p.photoId, PHOTO_ID) ? f.photoTemplate.replace("{photo}", p.photoId) : undefined;
  return f.photoBase.startsWith("https://") ? `${f.photoBase}${p.photoId}/image.jpg` : undefined;
}

/** "Sainsbury's" stays "Sainsbury's", "Morrisons" -> "Morrisons'", "Tesco" -> "Tesco's", "M&S" -> "M&S's" (never a doubled possessive). */

// Official restaurant logos, shown unmodified next to a chain's plain-text name to identify it (founder's decisions
// 2026-10-05 and 2026-10-06, see docs/PROGRESS.md and CLAUDE.md rule 2). A logo appears only if its file is listed here
// AND exists in public/logos/. Nothing is drawn or recreated by us: each file is the chain's own artwork, saved exactly as
// its own website serves it, and its source and terms are recorded in public/logos/SOURCES.md and <id>.source.txt.
// Remove a chain's line to take its logo down.
//
// `tile` is the plain neutral tile the file sits on: "light" (white, the default) or "dark" (near-black) for artwork the
// chain publishes in white for its own dark header. Never a brand colour.

export interface ChainLogo {
  src: string;
  tile?: "light" | "dark";
  /**
   * The chain's own SQUARE icon (the app icon its website serves: apple-touch-icon / web-app manifest icon / SVG site icon), saved
   * unchanged in public/logos/square/ with its record (founder 2026-10-11: "All logos should be 1:1"). Every logo tile is square, so this is
   * shown in preference to `src` (a wide wordmark can't be made square without cropping, which rule 2 forbids). `full`: the icon fills its
   * square (drawn edge to edge); otherwise it sits on the plain `tile`.
   */
  square?: { src: string; full?: boolean; tile?: "light" | "dark" };
}

/** What a square tile shows: the chain's square icon if it has one, else its logo file contained on its plain tile. */
export function tileArt(logo: ChainLogo): { src: string; full: boolean; tile: "light" | "dark"; fallback?: string } {
  if (logo.square) return { src: logo.square.src, full: !!logo.square.full, tile: logo.square.tile ?? "light", fallback: logo.square.src === logo.src ? undefined : logo.src };
  return { src: logo.src, full: false, tile: logo.tile ?? "light" };
}


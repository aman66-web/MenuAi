import { readFileSync, writeFileSync } from "node:fs";
import { expect, it } from "vitest";
import { RECIPES } from "../lib/mm/recipeBook";
import { recipeTotals, resolveRecipe } from "../lib/mm/recipes";
import { SCAN_RECIPE_REFS } from "../lib/mm/scanRecipeRefs";
import { decodeShopProducts } from "../lib/mm/shopProducts";

// Our recipes as reference dishes for Scan food (founder 2026-11-18: "you can also use from the recipes section ... to help"): each recipe as written, made at
// Sainsbury's (the shop whose labels we have for every recipe), with one serving's calories, protein, carbs and fat worked out from the products' labels, and
// what one serving is made of. Regenerate after the recipes or Sainsbury's labels change:
//   WRITE_SCAN_REFS=1 npx vitest run tests/scanRecipeRefs.test.ts
const SHOP = "sainsburys";

it("lib/mm/scanRecipeRefs.ts matches the recipes worked out from Sainsbury's labels", () => {
  const products = decodeShopProducts(JSON.parse(readFileSync(`public/groceries/all/${SHOP}.json`, "utf8")));
  const rows: string[] = [];
  const out: Array<{ name: string; kcal: number; protein: number; carbs: number; fat: number; portion: string }> = [];
  for (const recipe of RECIPES) {
    const totals = recipeTotals(resolveRecipe(recipe, products));
    if (!totals) continue;
    const s = totals.perServing;
    const portion = recipe.ingredients
      .map((i) => `${i.label.toLowerCase()} ${Math.round(i.amount / recipe.servings)} ${i.unit}`)
      .join(", ");
    const row = { name: recipe.name, kcal: Math.round(s.kcal), protein: Math.round(s.protein * 10) / 10, carbs: Math.round(s.carbs * 10) / 10, fat: Math.round(s.fat * 10) / 10, portion };
    out.push(row);
    rows.push(`  ${JSON.stringify(row)},`);
  }
  if (process.env.WRITE_SCAN_REFS) {
    writeFileSync("lib/mm/scanRecipeRefs.ts", `// Generated by tests/scanRecipeRefs.test.ts (WRITE_SCAN_REFS=1): each of our recipes as written, made at Sainsbury's, one serving's figures from the\n// products' labels and what one serving is made of. Reference dishes for Scan food (lib/mm/foodScan.ts); never shown. Don't edit by hand.\nexport const SCAN_RECIPE_REFS: ReadonlyArray<{ name: string; kcal: number; protein: number; carbs: number; fat: number; portion: string }> = [\n${rows.join("\n")}\n];\n`);
    return;
  }
  expect(SCAN_RECIPE_REFS).toEqual(out);
  expect(out.length).toBeGreaterThan(100);
}, 300_000);

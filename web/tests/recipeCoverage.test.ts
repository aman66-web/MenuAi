import { readFileSync, writeFileSync } from "node:fs";
import { expect, it } from "vitest";
import { RECIPES } from "../lib/mm/recipeBook";
import { resolveRecipe } from "../lib/mm/recipes";
import { RECIPE_COVERAGE } from "../lib/mm/recipeCoverage";
import { decodeShopProducts, type ShopManifest } from "../lib/mm/shopProducts";

// How many of our recipes each shop can make entirely from its own products with numbers: the shop's own label, or community numbers for the product's exact
// barcode (founder 2026-11-17: recipes from the shop the person picks, for every supermarket in the app).
// A shop counts for recipes only from MIN_RECIPE_COVERAGE (lib/mm/shopProducts.ts recipeShops). Regenerate after a shop's labels or list change:
//   WRITE_COVERAGE=1 npx vitest run tests/recipeCoverage.test.ts
it("lib/mm/recipeCoverage.ts matches the published shop lists", () => {
  const manifest = JSON.parse(readFileSync("public/groceries/all/all-manifest.json", "utf8")) as ShopManifest;
  const counts: Record<string, number> = {};
  for (const r of manifest.retailers) {
    if (!(r.nutrition ?? 0)) continue;
    const products = decodeShopProducts(JSON.parse(readFileSync(`public/groceries/all/${r.file}`, "utf8")));
    counts[r.id] = RECIPES.filter((recipe) => resolveRecipe(recipe, products).picks.every(Boolean)).length;
  }
  if (process.env.WRITE_COVERAGE) {
    const body = Object.entries(counts).map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join("\n");
    writeFileSync("lib/mm/recipeCoverage.ts", `// Generated by tests/recipeCoverage.test.ts (WRITE_COVERAGE=1): how many of the ${RECIPES.length} recipes each shop can make entirely from its own products\n// with numbers (its own label, or community numbers for the barcode). Don't edit by hand.\nexport const RECIPE_COVERAGE: Readonly<Record<string, number>> = {\n${body}\n};\n`);
    return;
  }
  expect(RECIPE_COVERAGE).toEqual(counts);
}, 300_000);
